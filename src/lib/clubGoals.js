export function nextSteps(metrics, target, horizon) {
  if (!metrics || !target) return []
  const {current, previous}=metrics
  const first = current >= target
    ? ['hold','Цель достигнута. Проверить, выдерживают ли группы эту нагрузку четыре недели подряд.']
    : current === 0
    ? ['measure','Проверить, отмечают ли тренеры участников. Провести одно пробное занятие и отметить пришедших.']
    : current < previous
    ? ['retain','Начать с удержания. Посмотреть, кто перестал ходить, выяснить препятствие и предложить удобное занятие.']
    : ['recruit','Проверить свободные места по группам. Направить следующий набор туда, где есть тренер и место.']
  return [first, [horizon.id,horizon.step], ['review','Сверить фактическую посещаемость с целью. Если разрыв остался, выбрать одно изменение для следующего цикла.']]
}
