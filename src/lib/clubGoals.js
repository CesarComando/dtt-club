// The server returns one row per Riga calendar week, including the current week.
export function weeklyBaseline(weeks) {
  const complete = weeks.slice(0, -1).slice(-8)
  if (complete.length < 8 || complete.some(w => !Number.isFinite(w.people) || w.people < 0)) return null
  const mean = rows => rows.reduce((sum, row) => sum + row.people, 0) / rows.length
  return {current: mean(complete.slice(4)), previous: mean(complete.slice(0, 4)), lastWeek: complete.at(-1).week_start}
}

